export class cursor {
    public hotspot_x: number = 0;
    public hotspot_y: number = 0;
    public width: number = 0;
    public height: number = 0;
    public data: string[] = null;
    public constructor(...args: any[]) {
        args.length >= 1 && (this.hotspot_x = args[0]);
        args.length >= 2 && (this.hotspot_y = args[1]);
        args.length >= 3 && (this.width = args[2]);
        args.length >= 4 && (this.height = args[3]);
        args.length >= 5 && (this.data = args[4]);
    }
}
