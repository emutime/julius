export function input_cursor_data(cursor_id: cursor_shape, scale: cursor_scale) {
    switch (cursor_id) {
        case CURSOR_ARROW:
            return ARROW[scale];
        case CURSOR_SHOVEL:
            return SHOVEL[scale];
        case CURSOR_SWORD:
            return SWORD[scale];
        default: return 0
    }
}
export function input_cursor_update(window: window_id) {
    if (window == WINDOW_CITY_MILITARY && !window_city_military_is_cursor_in_menu()) {
        system_set_cursor(CURSOR_SWORD);
    } else if (window == WINDOW_CITY && building_construction_type() == BUILDING_CLEAR_LAND) {
        system_set_cursor(CURSOR_SHOVEL);
    } else {
        system_set_cursor(CURSOR_ARROW);
    }
}
