function calculate_utf8_value(bytes: number, length: number) {
    let value: number = 0;
    if (length >= 1) {
        value |= bytes[0]
    }
    if (length >= 2) {
        value |= bytes[1] << 8
    }
    if (length >= 3) {
        value |= bytes[2] << 16
    }
    if (length >= 4) {
        value |= bytes[3] << 24
    }
    return value;
}
